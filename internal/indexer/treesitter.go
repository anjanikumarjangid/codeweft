package indexer

import (
	"context"
	"regexp"
	"strings"
	"unicode"

	sitter "github.com/smacker/go-tree-sitter"
)

// parseTree parses src with a tree-sitter grammar. A parser is created per
// call because tree-sitter parsers are not safe for concurrent use, and files
// are parsed in parallel.
func parseTree(lang *sitter.Language, src []byte) (*sitter.Node, func(), error) {
	p := sitter.NewParser()
	p.SetLanguage(lang)
	tree, err := p.ParseCtx(context.Background(), nil, src)
	if err != nil {
		p.Close()
		return nil, nil, err
	}
	return tree.RootNode(), func() { tree.Close(); p.Close() }, nil
}

func text(n *sitter.Node, src []byte) string {
	if n == nil {
		return ""
	}
	return n.Content(src)
}

func field(n *sitter.Node, name string) *sitter.Node {
	if n == nil {
		return nil
	}
	return n.ChildByFieldName(name)
}

func line(n *sitter.Node) int { return int(n.StartPoint().Row) + 1 }

func endLine(n *sitter.Node) int { return int(n.EndPoint().Row) + 1 }

func namedChildren(n *sitter.Node) []*sitter.Node {
	if n == nil {
		return nil
	}
	out := make([]*sitter.Node, 0, n.NamedChildCount())
	for i := 0; i < int(n.NamedChildCount()); i++ {
		out = append(out, n.NamedChild(i))
	}
	return out
}

// walk visits n and all its named descendants depth-first. Returning false
// from fn skips the node's children.
func walk(n *sitter.Node, fn func(*sitter.Node) bool) {
	if n == nil || !fn(n) {
		return
	}
	for _, c := range namedChildren(n) {
		walk(c, fn)
	}
}

// header returns the source of a declaration up to its body, with runs of
// whitespace collapsed: "public Order place(String id, List<String> items)".
func header(n, body *sitter.Node, src []byte) string {
	end := n.EndByte()
	if body != nil {
		end = body.StartByte()
	}
	return strings.TrimSuffix(strings.Join(strings.Fields(string(src[n.StartByte():end])), " "), ";")
}

var genericGenerated = regexp.MustCompile(`(?i)(auto-?generated|generated by|code generated).*(do not edit|don't edit)`)

// isGeneratedHeader looks for a "generated ... do not edit" marker near the
// top of a file, in any comment style.
func isGeneratedHeader(src []byte) bool {
	head := src
	if len(head) > 2048 {
		head = head[:2048]
	}
	return genericGenerated.Match(head) || strings.Contains(string(head), "@javax.annotation.Generated") ||
		strings.Contains(string(head), "@javax.annotation.processing.Generated")
}

func isCapitalized(s string) bool {
	for _, r := range s {
		return unicode.IsUpper(r)
	}
	return false
}

// cleanDocComment turns a /** ... */ block into plain text.
func cleanDocComment(c string) string {
	c = strings.TrimSuffix(strings.TrimPrefix(c, "/**"), "*/")
	lines := strings.Split(c, "\n")
	for i, l := range lines {
		l = strings.TrimSpace(l)
		l = strings.TrimPrefix(l, "*")
		lines[i] = strings.TrimSpace(l)
	}
	return strings.TrimSpace(strings.Join(lines, "\n"))
}

// dedent removes common leading indentation, for Python docstrings.
func dedent(s string) string {
	lines := strings.Split(strings.TrimSpace(s), "\n")
	indent := -1
	for _, l := range lines[1:] {
		if strings.TrimSpace(l) == "" {
			continue
		}
		n := len(l) - len(strings.TrimLeft(l, " \t"))
		if indent < 0 || n < indent {
			indent = n
		}
	}
	for i := 1; i < len(lines); i++ {
		if indent > 0 && len(lines[i]) >= indent {
			lines[i] = lines[i][indent:]
		}
	}
	return strings.Join(lines, "\n")
}
